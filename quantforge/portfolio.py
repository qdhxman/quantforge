"""Cash / position bookkeeping with realised PnL and cost accounting."""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Position:
    symbol: str
    qty: float = 0.0
    avg_cost: float = 0.0


class Portfolio:
    def __init__(self, cash: float):
        self.cash = float(cash)
        self.initial_cash = float(cash)
        self.positions: dict[str, Position] = {}
        self.last_prices: dict[str, float] = {}
        self.realized_pnl = 0.0
        self.total_commission = 0.0
        self.total_slippage = 0.0
        self.trade_count = 0

    def set_price(self, symbol: str, price: float) -> None:
        self.last_prices[symbol] = float(price)

    def position_value(self, symbol: str) -> float:
        p = self.positions.get(symbol)
        if not p or p.qty == 0:
            return 0.0
        return p.qty * self.last_prices.get(symbol, p.avg_cost)

    def long_value(self) -> float:
        return sum(v for v in (self.position_value(s) for s in self.positions) if v > 0)

    def gross_exposure(self) -> float:
        return sum(abs(self.position_value(s)) for s in self.positions)

    def equity(self) -> float:
        return self.cash + sum(self.position_value(s) for s in self.positions)

    def apply_fill(self, symbol: str, side_value: str, qty: float, price: float,
                   commission: float = 0.0, slippage: float = 0.0) -> float:
        """Apply a fill. Returns realised PnL generated by this fill."""
        if qty <= 0 or price <= 0:
            raise ValueError("fill qty and price must be positive")
        signed = qty if side_value == "BUY" else -qty
        pos = self.positions.get(symbol) or Position(symbol)
        old_qty, old_cost = pos.qty, pos.avg_cost
        new_qty = old_qty + signed
        realized = 0.0

        if old_qty == 0 or old_qty * signed > 0:
            # opening or adding in the same direction
            new_cost = (abs(old_qty) * old_cost + qty * price) / (abs(old_qty) + qty)
        else:
            closed = min(abs(signed), abs(old_qty))
            direction = 1.0 if old_qty > 0 else -1.0
            realized = (price - old_cost) * closed * direction
            self.realized_pnl += realized
            new_cost = price if abs(signed) > abs(old_qty) else old_cost

        self.cash -= signed * price
        self.cash -= commission
        self.total_commission += commission
        self.total_slippage += slippage
        self.trade_count += 1
        self.set_price(symbol, price)
        if abs(new_qty) < 1e-9:
            self.positions.pop(symbol, None)
        else:
            pos.qty, pos.avg_cost = new_qty, new_cost
            self.positions[symbol] = pos
        return realized

    def snapshot(self) -> dict[str, object]:
        return {
            "cash": round(self.cash, 2),
            "equity": round(self.equity(), 2),
            "gross_exposure": round(self.gross_exposure(), 2),
            "realized_pnl": round(self.realized_pnl, 2),
            "total_commission": round(self.total_commission, 2),
            "total_slippage": round(self.total_slippage, 2),
            "trade_count": self.trade_count,
            "positions": [
                {"symbol": p.symbol, "qty": round(p.qty, 4), "avg_cost": round(p.avg_cost, 4),
                 "market_value": round(self.position_value(p.symbol), 2)}
                for p in self.positions.values() if abs(p.qty) > 1e-9
            ],
        }
