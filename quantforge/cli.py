"""Command line entry point. Run ``quantforge --help`` after install."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Sequence

from .backtest import BacktestEngine
from .brokers import PaperBroker
from .config import default_config, load_config
from .data import dataset_to_jsonable, generate_synthetic, load_csv, slice_dataset
from .factors import list_factors
from .journal import Journal
from .live import LiveTradingEngine
from .risk import list_rules

ROOT = Path(__file__).resolve().parent.parent


def _common(p: argparse.ArgumentParser) -> None:
    p.add_argument("-c", "--config", help="strategy .json/.yaml file (default: built-in momentum-blend)")
    p.add_argument("--csv", help="long-format OHLCV CSV instead of the bundled synthetic sample")
    p.add_argument("--start", help="inclusive start date YYYY-MM-DD")
    p.add_argument("--end", help="inclusive end date YYYY-MM-DD")
    p.add_argument("--bars", type=int, default=504, help="synthetic sample length (default 504)")
    p.add_argument("--seed", type=int, default=20260101, help="synthetic sample seed")


def _data(args):
    raw = load_csv(args.csv) if getattr(args, "csv", None) else generate_synthetic(args.bars, args.seed)
    return slice_dataset(raw, getattr(args, "start", None), getattr(args, "end", None))


def _cfg(args):
    return load_config(getattr(args, "config", None))


def cmd_factors(args) -> int:
    rows = list_factors()
    if args.json:
        print(json.dumps(rows, ensure_ascii=False, indent=2))
    else:
        print(f"{'name':<16}{'category':<8}{'factor':<14}description")
        print("-" * 100)
        for r in rows:
            print(f"{r['name']:<16}{r['category']:<8}{r['label']:<14}{r['description']}")
    return 0


def cmd_rules(args) -> int:
    print(json.dumps(list_rules(), ensure_ascii=False, indent=2) if args.json else
          "\n".join(f"{r['rule']:<22}{r['label']:<12}{r['description']}" for r in list_rules()))
    return 0


def cmd_backtest(args) -> int:
    cfg, data = _cfg(args), _data(args)
    result = BacktestEngine(cfg).run(data)
    print(result.summary())
    if args.report:
        Path(args.report).write_text(result.markdown(), encoding="utf-8")
        print(f"markdown report -> {args.report}")
    if args.out:
        Path(args.out).write_text(json.dumps(result.as_dict(), ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"full result -> {args.out}")
    return 0


def cmd_signals(args) -> int:
    from .signals import SignalEngine
    cfg, data = _cfg(args), _data(args)
    engine = SignalEngine(cfg)
    out = []
    for symbol, bars in data.items():
        if symbol in cfg.symbols and bars:
            out.append(engine.evaluate(bars, len(bars) - 1, symbol).as_dict())
    print(json.dumps(out, ensure_ascii=False, indent=2))
    return 0


def cmd_paper(args) -> int:
    cfg, data = _cfg(args), _data(args)
    cfg.trading.mode = "paper"
    broker = PaperBroker(cfg.backtest.initial_cash, cfg.backtest.commission_bps, cfg.backtest.slippage_bps)
    journal = Journal(args.journal)
    engine = LiveTradingEngine(cfg, broker, data, journal=journal)
    engine.run(interval_seconds=0, max_cycles=args.steps)
    summary = {
        "cycles": engine.status()["cycles"],
        "account": broker.get_account(),
        "orders": sum(1 for e in journal.events if e["type"] == "ORDER_SUBMITTED"),
        "risk_blocks": sum(1 for e in journal.events if e["type"] == "RISK_BLOCK"),
        "journal": args.journal,
    }
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


def cmd_serve(args) -> int:
    try:
        import uvicorn
    except ImportError:
        print("API extra missing. Run: pip install -e '.[api]'", file=sys.stderr)
        return 2
    from .api import create_app
    data = load_csv(args.csv) if args.csv else generate_synthetic(args.bars, args.seed)
    app = create_app(config=_cfg(args), data=data)
    print(f"QuantForge API -> http://{args.host}:{args.port}/docs")
    uvicorn.run(app, host=args.host, port=args.port)
    return 0


def cmd_sample_data(args) -> int:
    data = generate_synthetic(args.bars, args.seed)
    payload = {
        "meta": {"source": "synthetic", "seed": args.seed, "bars": args.bars,
                 "note": "Synthetic OHLCV generated by quantforge.data.generate_synthetic; NOT real market data."},
        "data": dataset_to_jsonable(data),
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    js = "(function(){var d=" + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";" \
         "if(typeof module==='object'&&module.exports){module.exports=d;}" \
         "if(typeof window!=='undefined'){window.QF_DATA=d;}})();\n"
    out.write_text(js, encoding="utf-8")
    print(f"wrote {out} ({len(data)} symbols x {args.bars} bars)")

    # Presets are generated from the very same strategy files the CLI/API load,
    # so the browser demo and the Python engine cannot drift apart.
    strategies = ROOT / "config" / "strategies"
    presets = {
        "momentum": json.loads((strategies / "momentum.json").read_text(encoding="utf-8")),
        "mean_reversion": json.loads((strategies / "mean_reversion.json").read_text(encoding="utf-8")),
        "breakout": {
            "name": "aggressive-breakout",
            "description": "最激进的 max 组合 + 低阈值 + 双倍成本，用来观察激进配置的代价",
            "symbols": ["AAPL", "MSFT", "NVDA", "SPY"],
            "factors": [
                {"name": "breakout", "weight": 1.0, "params": {"channel": 20}},
                {"name": "atr_trend", "weight": 0.8, "params": {"period": 14}},
                {"name": "volume_spike", "weight": 0.6, "params": {"period": 20}},
            ],
            "signal": {"buy_threshold": 0.12, "sell_threshold": -0.12, "smoothing": 0.0,
                       "min_holding_bars": 1, "combine_method": "max"},
            "backtest": {"initial_cash": 100000.0, "commission_bps": 10.0, "slippage_bps": 8.0,
                         "lot_size": 1, "min_order_value": 500.0, "max_position_pct": 0.4,
                         "max_gross_exposure_pct": 1.0, "allow_short": False},
            "risk": {"max_order_notional": 40000.0, "max_position_pct": 0.4,
                     "max_gross_exposure_pct": 1.0, "max_daily_loss_pct": 0.05,
                     "max_drawdown_pct": 0.25, "cooldown_bars": 1, "blacklist": [],
                     "kill_switch": False, "allow_short": False},
            "trading": {"mode": "paper", "poll_seconds": 60, "journal_path": "logs/trading-journal.jsonl",
                        "order_type": "market", "max_orders_per_cycle": 10},
        },
    }
    presets_out = ROOT / "web" / "presets.js"
    pjs = "(function(){var p=" + json.dumps(presets, ensure_ascii=False, separators=(",", ":")) + ";" \
          "if(typeof module==='object'&&module.exports){module.exports=p;}" \
          "if(typeof window!=='undefined'){window.QF_PRESETS=p;}})();\n"
    presets_out.write_text(pjs, encoding="utf-8")
    print(f"wrote {presets_out} ({len(presets)} presets)")

    if args.csv:
        import csv as _csv
        p = Path(args.csv)
        p.parent.mkdir(parents=True, exist_ok=True)
        with p.open("w", encoding="utf-8", newline="") as fh:
            w = _csv.writer(fh)
            w.writerow(["date", "symbol", "open", "high", "low", "close", "volume"])
            for symbol, bars in data.items():
                for b in bars:
                    w.writerow([b.date, symbol, b.open, b.high, b.low, b.close, b.volume])
        print(f"wrote {p}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="quantforge", description="QuantForge - factor research, backtesting and guarded execution")
    p.add_argument("--version", action="version", version="quantforge 0.1.0")
    sub = p.add_subparsers(dest="command", required=True)

    f = sub.add_parser("factors", help="list available factors")
    _common(f)
    f.add_argument("--json", action="store_true")
    f.set_defaults(func=cmd_factors)

    r = sub.add_parser("rules", help="list risk control rules")
    r.add_argument("--json", action="store_true")
    r.set_defaults(func=cmd_rules)

    b = sub.add_parser("backtest", help="run a backtest")
    _common(b)
    b.add_argument("--report", help="write a markdown report to this path")
    b.add_argument("--out", help="write full result JSON to this path")
    b.set_defaults(func=cmd_backtest)

    s = sub.add_parser("signals", help="show the latest signals")
    _common(s)
    s.set_defaults(func=cmd_signals)

    pp = sub.add_parser("paper", help="run the autonomous loop against the paper broker")
    _common(pp)
    pp.add_argument("--steps", type=int, default=20, help="number of cycles (default 20)")
    pp.add_argument("--journal", default="logs/trading-journal.jsonl")
    pp.set_defaults(func=cmd_paper)

    sv = sub.add_parser("serve", help="start the FastAPI service + dashboard")
    _common(sv)
    sv.add_argument("--host", default="127.0.0.1")
    sv.add_argument("--port", type=int, default=8000)
    sv.set_defaults(func=cmd_serve)

    sd = sub.add_parser("sample-data", help="regenerate the browser demo dataset")
    sd.add_argument("--out", default=str(ROOT / "web" / "data.js"))
    sd.add_argument("--csv", help="also write a long-format CSV to this path")
    sd.add_argument("--bars", type=int, default=504)
    sd.add_argument("--seed", type=int, default=20260101)
    sd.set_defaults(func=cmd_sample_data)
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
